#!/usr/bin/env node
// Bundles samples/*.txt into js/samples-data.js so the demo works offline,
// from file://, and on GitHub Pages without extra fetches.
// Run: node scripts/build-samples.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'samples');
const META = {
  'sample-1-unfair-condo-cheras.txt': 'Unfair condo TA (Cheras) — many red flags',
  'sample-2-balanced-apartment-pj.txt': 'Balanced apartment TA (Petaling Jaya)',
  'sample-3-room-rental-subang.txt': 'Room rental, no clause numbers (Subang Jaya)'
};
const samples = fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort().map((f) => ({
  id: f.replace(/\.txt$/, ''),
  title: META[f] || f,
  file: 'samples/' + f,
  text: fs.readFileSync(path.join(dir, f), 'utf8')
}));
const out = '/* AUTO-GENERATED by scripts/build-samples.js — do not edit by hand. */\n' +
  'window.SEWA_SAMPLES = ' + JSON.stringify(samples, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'js', 'samples-data.js'), out);
console.log('Wrote js/samples-data.js with', samples.length, 'samples');
